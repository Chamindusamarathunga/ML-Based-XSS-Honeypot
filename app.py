@app.route('/search', methods=['GET', 'POST'])
def search_endpoint():
    query = request.args.get('q', '') if request.method == 'GET' else \
            (request.form.get('q', '') or (request.get_json().get('q', '') if request.is_json else ''))
    
    # Honey-field check
    h_field = request.args.get('url_callback') or request.form.get('url_callback')
    if h_field:
        log_attack('bot_detection', f"Honey-field 'url_callback' filled with: {h_field}", {'is_suspicious': True, 'detected_patterns': ['Honey-field Triggered']})
        
    client = get_client_info()
    det_results = detector.detect(query)
    
    search = SearchLog(search_query=query, ip_address=client['ip_address'], is_suspicious=det_results['is_suspicious'])
    db.session.add(search)
    db.session.commit()
    
    if det_results['is_suspicious']:
        log_attack('reflected_xss', query, det_results)
        
    return render_template('index.html', query=query)

@app.route('/api/add-comment', methods=['POST'])
def add_comment():
    data = request.get_json() if request.is_json else request.form
    
    # Honey-field check
    if data.get('form_token'):
        log_attack('bot_detection', f"Honey-field 'form_token' filled with: {data.get('form_token')}", {'is_suspicious': True, 'detected_patterns': ['Honey-field Triggered']})

    name, email, comment_text = data.get('name', ''), data.get('email', ''), data.get('comment', '')
    det_name, det_email, det_comment = detector.detect(name), detector.detect(email), detector.detect(comment_text)
    
    is_attack = any([det_name['is_suspicious'], det_email['is_suspicious'], det_comment['is_suspicious']])
    comment_rec = Comment(name=name, email=email, comment_text=comment_text, is_attack=is_attack)
    db.session.add(comment_rec)
    db.session.commit()
    
    if is_attack:
        log_attack('stored_xss', f"Name: {name} | Email: {email} | Comment: {comment_text}", {'name': det_name, 'email': det_email, 'comment': det_comment})
        
    return jsonify({'success': True, 'message': 'Comment added'})

