def get_client_info():
    ip = request.headers.get('X-Forwarded-For', request.remote_addr)
    return {
        'ip_address': ip,
        'user_agent': request.headers.get('User-Agent', 'Unknown'),
        'referer': request.headers.get('Referer', 'Direct'),
        'method': request.method
    }

def log_attack(attack_type, payload, detection_results):
    client = get_client_info()
    geodata = intel.get_geoip(client['ip_address'])
    bot_identity = intel.identify_bot(client['user_agent'])
    rdns = intel.reverse_dns(client['ip_address'])
    
    # Check for behavioral anomalies
    is_aggressive, count = behavior.check_behavior(client['ip_address'])
    if is_aggressive: bot_identity = f"Aggressive Scanner ({count} req/min)"
    
    intelligence_data = {'geoip': geodata, 'bot_identity': bot_identity, 'reverse_dns': rdns}
    
    log = AttackLog(
        attack_type=attack_type, payload=payload, payload_hash=hashlib.sha256(payload.encode()).hexdigest(),
        ip_address=client['ip_address'], user_agent=client['user_agent'], referer=client['referer'],
        method=client['method'], detection_results=json.dumps(detection_results), intelligence=json.dumps(intelligence_data)
    )
    db.session.add(log)
    db.session.commit()
    
    # --- JSON File Logging ---
    try:
        log_entry = {
            'attack_type': attack_type,
            'payload': payload,
            'client_info': client,
            'intelligence': intelligence_data,
            'detection_results': detection_results,
            'timestamp': datetime.utcnow().isoformat()
        }
        filename = f"attack_{datetime.utcnow().strftime('%Y%m%d_%H%M%S_%f')}.json"
        log_path = os.path.join('honeypot_logs', filename)
        with open(log_path, 'w') as f:
            json.dump(log_entry, f, indent=4)
    except Exception as e:
        print(f"Error writing JSON log: {e}")

    webhooks.send_alert(log, intelligence_data)

