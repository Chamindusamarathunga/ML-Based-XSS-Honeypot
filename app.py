class PayloadDeobfuscator:
    @staticmethod
    def deobfuscate(text):
        if not text: return ""
        
        # 1. URL Decoding
        try:
            text = unquote(text)
        except: pass
        
        # 2. Base64 attempts
        b64_matches = re.findall(r'[A-Za-z0-9+/]{8,}=*', text)
        for match in b64_matches:
            try:
                decoded = base64.b64decode(match).decode('utf-8', errors='ignore')
                if any(kw in decoded.lower() for kw in ['script', 'alert', 'onload', 'onerror', 'eval']):
                    text = text.replace(match, decoded)
            except: pass
            
        # 3. String.fromCharCode
        char_code_matches = re.findall(r'String\.fromCharCode\((.*?)\)', text, re.I)
        for match in char_code_matches:
            try:
                chars = [chr(int(c.strip())) for c in match.split(',')]
                decoded = "".join(chars)
                text = text.replace(f"String.fromCharCode({match})", decoded)
            except: pass
            
        return text

class XSSDetector:
    # ── Paths to ML model artifacts (generated by train_model.py) ─────────────
    ML_MODEL_PATH      = os.path.join('ml_model', 'xss_model.pkl')
    ML_VECTORIZER_PATH = os.path.join('ml_model', 'tfidf_vectorizer.pkl')
    # Confidence threshold: ML prediction probability above this → XSS
    ML_CONFIDENCE_THRESHOLD = 0.60

    def __init__(self, payloads_dir):
        self.payloads_dir = payloads_dir
        self.core_patterns = [
            r'<script[^>]*>', r'javascript:', r'on\w+\s*=', r'alert\(',
            r'prompt\(', r'confirm\(', r'<svg[^>]*onload', r'onerror\s*=',
            r'document\.cookie', r'eval\(', r'base64', r'data:text/html',
            r'<iframe[^>]*', r'<object[^>]*', r'vbscript:'
        ]
        self.signatures = []
        self.load_signatures()
        self.deobfuscator = PayloadDeobfuscator()
        self._load_ml_model()

    def _load_ml_model(self):
        """Load the trained scikit-learn ML model and TF-IDF vectorizer."""
        self.ml_model      = None
        self.ml_vectorizer = None
        try:
            if os.path.exists(self.ML_MODEL_PATH) and os.path.exists(self.ML_VECTORIZER_PATH):
                self.ml_model      = joblib.load(self.ML_MODEL_PATH)
                self.ml_vectorizer = joblib.load(self.ML_VECTORIZER_PATH)
                print("[ML] XSS detection model loaded successfully.")
            else:
                print("[ML] WARNING: Model artifacts not found. "
                      "Run 'python train_model.py' to generate them. "
                      "Falling back to regex-only detection.")
        except Exception as e:
            print(f"[ML] ERROR loading model: {e}. Falling back to regex-only detection.")

    def load_signatures(self):
        self.signatures = list(self.core_patterns)
        if os.path.exists(self.payloads_dir):
            payload_files = glob.glob(os.path.join(self.payloads_dir, "*.txt"))
            for file_path in payload_files:
                try:
                    with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                        for line in f:
                            line = line.strip()
                            if line and len(line) > 8:
                                self.signatures.append(re.escape(line))
                except: pass
        print(f"[Signatures] Loaded {len(self.signatures)} XSS signatures.")

    def _ml_predict(self, text: str) -> dict:
        """Run the ML model and return prediction label and confidence.

        Returns:
            dict with keys:
                ml_is_xss     (bool)   – True if ML predicts XSS
                ml_confidence (float)  – Probability score [0.0 – 1.0] for XSS class
                ml_available  (bool)   – False when model artifacts are not loaded
        """
        if self.ml_model is None or self.ml_vectorizer is None:
            return {'ml_is_xss': False, 'ml_confidence': 0.0, 'ml_available': False}
        try:
            vec   = self.ml_vectorizer.transform([text])
            proba = self.ml_model.predict_proba(vec)[0]   # [P(benign), P(xss)]
            xss_prob = float(proba[1])
            return {
                'ml_is_xss':     xss_prob >= self.ML_CONFIDENCE_THRESHOLD,
                'ml_confidence': round(xss_prob, 4),
                'ml_available':  True
            }
        except Exception as e:
            print(f"[ML] Prediction error: {e}")
            return {'ml_is_xss': False, 'ml_confidence': 0.0, 'ml_available': False}

    def detect(self, input_string):
        """Combined regex + ML XSS detection.

        Detection strategy:
          1. De-obfuscate the input (URL decode, Base64, fromCharCode).
          2. Run regex/signature matching (fast, rule-based).
          3. Run ML model prediction (probabilistic).
          4. Flag as suspicious if EITHER method fires.

        Returns a dict suitable for JSON serialization and dashboard display.
        """
        if not input_string:
            return {
                'is_suspicious':        False,
                'detected_patterns':    [],
                'payload_length':       0,
                'ml_confidence':        0.0,
                'ml_available':         self.ml_model is not None,
                'detection_method':     'none'
            }

        # ── Step 1: De-obfuscate ────────────────────────────────────────────────
        deobfuscated = self.deobfuscator.deobfuscate(input_string)

        # ── Step 2: Regex / Signature detection ────────────────────────────────
        detected_patterns = []
        for pattern in self.core_patterns:
            if re.search(pattern, deobfuscated, re.IGNORECASE):
                detected_patterns.append(pattern)

        if len(detected_patterns) < 5:
            for pattern in self.signatures:
                if pattern in self.core_patterns:
                    continue
                try:
                    if re.search(pattern, deobfuscated, re.IGNORECASE):
                        detected_patterns.append(
                            pattern[:50] + '...' if len(pattern) > 50 else pattern
                        )
                        if len(detected_patterns) >= 10:
                            break
                except:
                    continue

        regex_hit = len(detected_patterns) > 0

        # ── Step 3: ML prediction ───────────────────────────────────────────────
        # Run on both original and de-obfuscated text (use whichever is more confident)
        ml_orig  = self._ml_predict(input_string)
        ml_deob  = self._ml_predict(deobfuscated)
        ml_conf  = max(ml_orig['ml_confidence'], ml_deob['ml_confidence'])
        ml_hit   = ml_conf >= self.ML_CONFIDENCE_THRESHOLD

        # Annotate detected_patterns with ML score for transparency
        if ml_hit and ml_orig['ml_available']:
            detected_patterns.append(
                f"[ML Model] XSS probability: {ml_conf * 100:.1f}%"
            )

        # ── Step 4: Combine ─────────────────────────────────────────────────────
        is_suspicious = regex_hit or ml_hit

        if regex_hit and ml_hit:
            detection_method = 'regex+ml'
        elif regex_hit:
            detection_method = 'regex'
        elif ml_hit:
            detection_method = 'ml_only'
        else:
            detection_method = 'none'

        return {
            'is_suspicious':        is_suspicious,
            'detected_patterns':    detected_patterns,
            'original_length':      len(input_string),
            'deobfuscated_preview': deobfuscated[:100] if deobfuscated != input_string else None,
            'ml_confidence':        ml_conf,
            'ml_available':         ml_orig['ml_available'],
            'detection_method':     detection_method
        }

