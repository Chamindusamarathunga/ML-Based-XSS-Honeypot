class IntelligenceEngine:
    @staticmethod
    def get_geoip(ip):
        if ip in ['127.0.0.1', '::1']:
            return {'city': 'Localhost', 'country': 'Internal', 'isp': 'Private Network'}
        try:
            response = requests.get(f"http://ip-api.com/json/{ip}", timeout=3)
            if response.status_code == 200:
                data = response.json()
                if data['status'] == 'success':
                    return {'city': data.get('city'), 'country': data.get('country'), 'isp': data.get('isp')}
        except: pass
        return {}

    @staticmethod
    def identify_bot(user_agent):
        ua_lower = user_agent.lower()
        bots = {'burp': 'Burp Suite', 'zap': 'OWASP ZAP', 'sqlmap': 'sqlmap', 'nikto': 'Nikto', 'acunetix': 'Acunetix', 'python-requests': 'Python Scanner', 'curl': 'cURL Client', 'nmap': 'Nmap'}
        for key, name in bots.items():
            if key in ua_lower: return name
        return "Likely Manual"

    @staticmethod
    def reverse_dns(ip):
        try: return socket.gethostbyaddr(ip)[0]
        except: return "Unknown"

class BehavioralMonitor:
    def __init__(self):
        self.request_history = defaultdict(list)
        self.threshold = 30 # Requests per minute
        
    def check_behavior(self, ip):
        now = time.time()
        self.request_history[ip] = [t for t in self.request_history[ip] if now - t < 60]
        self.request_history[ip].append(now)
        
        if len(self.request_history[ip]) > self.threshold:
            return True, len(self.request_history[ip])
        return False, len(self.request_history[ip])

class WebhookManager:
    @staticmethod
    def send_alert(attack_log_entry, intelligence):
        webhook_url = os.getenv('DISCORD_WEBHOOK_URL') or os.getenv('SLACK_WEBHOOK_URL')
        if not webhook_url: return
        
        payload = {
            "content": f"🚨 **Honeypot Alert: {attack_log_entry.attack_type.upper()}**",
            "embeds": [{
                "title": "Attack Details",
                "color": 15158332 if attack_log_entry.attack_type != 'reflected_xss' else 3447003,
                "fields": [
                    {"name": "IP Address", "value": attack_log_entry.ip_address, "inline": True},
                    {"name": "Location", "value": f"{intelligence['geoip'].get('city', 'Unknown')}, {intelligence['geoip'].get('country', 'Unknown')}", "inline": True},
                    {"name": "Attribution", "value": intelligence['bot_identity'], "inline": True},
                    {"name": "Payload", "value": f"```{attack_log_entry.payload[:500]}```"}
                ],
                "footer": {"text": f"Event Hash: {attack_log_entry.payload_hash[:16]}"}
            }]
        }
        try: requests.post(webhook_url, json=payload, timeout=5)
        except: pass

